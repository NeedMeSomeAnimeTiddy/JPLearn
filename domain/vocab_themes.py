"""Hand-authored thematic groupings for the vocabulary level decks.

The same problem :mod:`domain.kanji_themes` solves, one deck family over: 377 of
the app's 405 vocabulary blocks were named ``"Words 1"`` … ``"Words 130"``. The
deck is ordered by romaji, so those blocks were alphabetical slices — 冷ます next
to 覚ます because both read ``samasu`` — which is not a study unit at all. All
five levels are now themed, so no block in the app is numbered.

Entries are *word surfaces*, so this is a tuple of strings rather than the packed
character string kanji uses: a vocabulary entry is many characters wide, and some
carry inline alternates (``足; 脚``, ``キロ; キログラム``). The surface must match
the deck's exactly; :mod:`tests.test_vocab_themes` asserts every one resolves, so
a corpus change fails loudly instead of silently dropping a word.

Headings must not collide with the authored category decks that run before them
(``Numbers``, ``Family``, ``Food & Drink``, ``School & Study`` at N5;
``Work & Business``, ``Emotion & Mind``, ``Society & People``, ``Nature & Science``
at N3) — two chips with one name is the ambiguity these exist to remove.

Themes group by subject, not by strict semantic field — a theme is a study unit of
roughly twenty, so a few members sit at the edge of their heading. Function words
and demonstratives get their own headings rather than being scattered: at N5 they
are a large, coherent and genuinely separate thing to learn.

Some levels need headings that are not subjects at all. N2 carries ~110 bound
affixes (``~泊``, ``反~``, ``~だらけ``) and ~50 fixed social phrases
(``お世話になりました``); both are split by what they *do* — what a counter counts,
what a prefix negates — rather than pooled under one number. N1 needs the same
for its own affixes and for the manner adverbs (``がっしり``/``ずるずる``), which
split by whether they describe something firm or something slack.

A heading that wants a roman numeral is a dumping ground, not a theme; the same
rule :mod:`domain.kanji_themes` learned the hard way applies here.
"""

